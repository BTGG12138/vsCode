/*
对外接口：函数声明、类、公开成员，用 /// 或 /** ... * / 写文档注释。
内部实现：函数体里的逻辑说明、临时备注，用普通 //。
成员变量尾随说明：用 ///<，例如 int count; ///< 当前元素个数。

对于常量，Google风格指南推荐使用以‘k’开头的驼峰命名法（例如：kDaysInWeek），这有助于在代码中快速识别常量。
char vs 其他三个：它是“字节”，不是“完整字符”
    char 保证 1 字节（sizeof(char)==1），但不保证是 8 位，也不保证是 UTF-8。
    在 Linux 上，std::string 通常存 UTF-8，一个汉字占 3 个 char，所以 size() 返回的是字节数，不是字符数。
    它同时也是小整数类型，适合做原始二进制缓冲。
wchar_t vs char16_t/char32_t：宽度是否固定
    wchar_t 的宽度由实现决定：Windows 2 字节，Linux 4 字节。同一段代码跨平台行为不同，这是它最大的坑。
    char16_t 固定 2 字节，char32_t 固定 4 字节，宽度由标准保证，更适合可移植的 Unicode 处理。
char16_t vs char32_t：UTF-16 码元 vs UTF-32 码点
    char16_t 是 UTF-16 的码元。基本多文种平面外的字符需要两个 char16_t（代理对） 表示，所以“一个 char16_t 不一定是一个字符”。
    char32_t 是 UTF-32 的码点。一个 char32_t 就是一个 Unicode 码点，概念最干净，但内存占用大。
*/
